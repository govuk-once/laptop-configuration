#!/usr/bin/env bash
# PreToolUse(Edit|Write|MultiEdit): block edits to generated or critical files.
set -uo pipefail

file=$(jq -r '.tool_input.file_path // empty')
[[ -z "$file" ]] && exit 0

block() {
  echo "Blocked: $file is $1. Do not edit it by hand." >&2
  exit 2
}

name=$(basename "$file")
case "$name" in
  CHANGELOG.md | CHANGELOG) block "a generated changelog" ;;
  pnpm-lock.yaml | package-lock.json | yarn.lock | .terraform.lock.hcl | poetry.lock | Cargo.lock) block "a lock file (regenerate it with the package manager or terraform init)" ;;
  *.tfstate | *.tfstate.*) block "Terraform state" ;;
esac

case "$file" in
  */.terraform/* | */.nx/* | */node_modules/* | */.git/*) block "inside a tool-managed directory" ;;
esac

# Files that declare themselves generated in their first lines
if [[ -f "$file" ]] && head -5 "$file" 2>/dev/null | grep -qiE 'auto-generated|autogenerated|do not edit|generated by'; then
  block "marked as auto-generated"
fi

exit 0
